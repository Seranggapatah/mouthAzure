#!/usr/bin/env python3
"""Embeds build/mouth_visame.riv into app/riv_data.js so app/index.html runs
straight from disk (no server needed).

After changing the rig:
    rive . --publish && python3 tools/build_app.py
"""
import base64
import os

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
SRC = os.path.join(ROOT, "build", "mouth_visame.riv")
DST = os.path.join(ROOT, "app", "riv_data.js")


def main():
    with open(SRC, "rb") as fh:
        data = fh.read()
    with open(DST, "w") as fh:
        fh.write("// Generated by tools/build_app.py from build/mouth_visame.riv - do not edit.\n")
        fh.write(f'window.RIV_BASE64 = "{base64.b64encode(data).decode()}";\n')
    print(f"wrote {DST} ({len(data)} bytes of riv)")


if __name__ == "__main__":
    main()
